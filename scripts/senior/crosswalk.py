"""The one reader of the vocabulary crosswalk's lineage rows.

``core/phenocycler/data/integration/vocab_crosswalk.csv`` is GENERATED by ``run_vocab`` in
``phenocycler/integration/vocab.py``: read, never hand-edited, and never filtered down to the
lineages that happen to agree.  Until 2026-09-24 three builders each read it their own way --
``build_grid_composition.py`` and ``modality_concordance.py`` as text with blanks filled,
``build_compartment_gradient.py`` with inferred types, matching ``is_immune`` case-insensitively
and turning a blank scope into the string ``"nan"``.  They now share this one, and it is strict:

* every column is text and a blank is ``""`` -- never NaN, never ``"nan"``;
* a value is what it says: ``"yes"`` is yes and ``"Yes"`` is not;
* a crosswalk with no lineage rows is refused, not read as an empty table.

On the crosswalk on disk the three builders get what they got before, value for value
(test_crosswalk_reader.py).

``build_distance_profiles.load_immune_vocabulary`` stays a reader of its own: it answers a
different question -- is-immune per lineage, or None where the file does not record it, so its
caller withholds by name -- and it already reads each value exactly.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from phenocycler.roots import INTEGRATION

CROSSWALK = INTEGRATION / "vocab_crosswalk.csv"


class CrosswalkError(ValueError):
    """The crosswalk cannot be read as a lineage table."""


def lineage_rows(path: str | Path = CROSSWALK) -> pd.DataFrame:
    """The crosswalk's ``kind == "lineage"`` rows, every column as text, a blank as ``""``."""
    table = pd.read_csv(path, dtype=str).fillna("")
    lineages = table[table["kind"].eq("lineage")].copy()
    if lineages.empty:
        raise CrosswalkError(f"{path} carries no lineage rows")
    return lineages
