"""declarations.json and rules_broad8.csv must be exactly what the rule produces.

The ``anchors.json`` idiom (``dct/tests/test_concordance_gate.py``): the frozen file is
regenerated by code from the two pre-existing declarations -- the marker registry and the
37-reference rule table -- and compared byte for byte.  A hand edit to either artifact, or
a change to the registry or the rule table, fails here instead of silently moving the label
space under every arm.

The tiering rule is asserted from the artifact itself: every identity marker is registry
``kind == 'type'``, no ``state`` marker appears in any label's markers OR negatives, and
Neural is undeclared for the recorded reason (its only registered marker, B3TUBB, fails the
conflict rule -- a consequence of the pre-registered rule, not of a result).
"""
from __future__ import annotations

import json

import pandas as pd

import declarations
import pins

PROTOCOL_LABELS = {
    "Endocrine": ["GCG", "INS", "SST"],
    "Epithelial_nonendocrine": ["E_cadherin", "EpCAM", "Ker8_18", "Keratin_5", "Pan_Cytokeratin", "TP63"],
    "Vascular": ["CD31", "Caveolin", "Podoplanin"],
    "Stromal": ["SMA", "Vimentin"],
    "T_NK": ["CD3e", "CD4", "CD8", "FOXP3"],
    "B_Plasma": ["CD20", "CD79a"],
    "Myeloid": ["CD11c", "CD163", "CD206", "CD209", "CD68", "Iba1", "M2Gal3", "MPO"],
}


# --------------------------------------------------------------------------- regeneration
def test_declarations_json_is_derived_not_typed():
    """Byte-exact: the same serialisation ``declarations.write`` uses, against the file."""
    fresh = declarations.derive()
    frozen_text = declarations.DECLARATIONS_JSON.read_text()
    assert json.dumps(fresh, indent=1, sort_keys=False) + "\n" == frozen_text
    assert json.loads(frozen_text) == fresh
    assert fresh["method_version"] == "broadtype-declarations-2026-09-17"


def test_declarations_record_the_sha_of_both_sources():
    """A registry or rule-table edit changes a recorded sha, so it cannot pass unnoticed."""
    frozen = declarations.load()
    assert frozen["sources"]["registry_sha256"] == declarations._sha(pins.REGISTRY)
    assert frozen["sources"]["rules_sha256"] == declarations._sha(pins.RULES_37)


def test_rules_broad8_csv_is_derived_not_typed():
    """Byte-exact against the v4 layout ``declarations.write`` emits (two unnamed lead columns)."""
    fresh = declarations.rules_broad8(declarations.derive())
    text = fresh.rename(columns={"parent": "", "phenotype": ""}).to_csv(index=False)
    assert text == declarations.RULES_BROAD8_CSV.read_text()


def test_rules_broad8_rows_are_the_declared_labels_with_their_markers_and_negatives(dec):
    """Each row: declared markers carry the positive token, negatives ``allneg``, nothing else."""
    import rules  # scripts/celltype/rules.py -- the frozen display -> registry crosswalk
    cw = rules.load_crosswalk(pins.RULES_37)
    table = declarations.rules_broad8(dec)
    assert table["phenotype"].tolist() == list(dec["labels"])
    assert (table["parent"] == "all").all()
    for _, row in table.iterrows():
        spec = dec["labels"][row["phenotype"]]
        pos_tok = "allpos" if len(spec["markers"]) == 1 else "anypos"
        filled = {cw[c]: row[c] for c in table.columns[2:] if row[c] != ""}
        assert {m for m, t in filled.items() if t == pos_tok} == set(spec["markers"])
        assert {m for m, t in filled.items() if t == "allneg"} == set(spec["negatives"])
        assert set(filled.values()) <= {pos_tok, "allneg"}


def test_the_csv_loads_through_the_celltype_rule_loader(dec):
    """The cosine arm reads this table with ``rules.load_rules``; it must parse as v4."""
    import rules
    table = rules.load_rules(declarations.RULES_BROAD8_CSV)
    assert list(table.columns[:2]) == ["parent", "phenotype"]
    assert table["phenotype"].tolist() == list(dec["labels"])
    # the loader maps display names to registry names, so declared markers are columns now
    for L, spec in dec["labels"].items():
        for m in spec["markers"]:
            assert m in table.columns, f"{L}: declared marker {m} has no column after the crosswalk"


# --------------------------------------------------------------------------- the tiering rule
def test_the_label_space_is_the_protocol_table(dec):
    assert {L: s["markers"] for L, s in dec["labels"].items()} == PROTOCOL_LABELS
    assert len(dec["labels"]) == 7
    assert set(dec["identity_markers"]) == {m for ms in PROTOCOL_LABELS.values() for m in ms}
    for L, spec in dec["labels"].items():
        assert spec["n_markers"] == len(spec["markers"])
        assert spec["held_out_gated"] == (len(spec["markers"]) >= 2 and L != "Endocrine")
        assert spec["common_lineage"] == declarations.COMMON[L]


def test_every_identity_marker_is_registry_kind_type(dec):
    by_kind = pins.markers_by_kind()
    kind = {m: k for k, ms in by_kind.items() for m in ms}
    for m in dec["identity_markers"]:
        assert kind[m] == pins.KIND_TYPE, f"{m} is registry kind={kind[m]!r}"
    for L, spec in dec["labels"].items():
        for m in spec["markers"]:
            assert kind[m] == pins.KIND_TYPE, f"{L}: {m} is registry kind={kind[m]!r}"
    assert dec["state_markers"] == by_kind[pins.KIND_STATE]
    assert dec["structural_markers"] == by_kind[pins.KIND_STRUCTURAL]


def test_no_state_marker_in_any_label_markers_or_negatives(dec):
    """State markers never enter identity -- not as evidence for a label, not against one."""
    state = set(dec["state_markers"])
    assert state, "the registry declares state markers; an empty set would make this vacuous"
    for L, spec in dec["labels"].items():
        assert not state & set(spec["markers"]), f"{L}: state marker in identity markers"
        assert not state & set(spec["negatives"]), f"{L}: state marker used as a negative"
    assert not state & set(dec["identity_markers"])
    # 23 original + 10 deferred state measurements added 2026-09-16 + CD45RO and IFNG, the
    # spleen PhenoCycler panel's deferred state markers (2026-10-30)
    assert len(state) == 35


def test_negatives_are_identity_markers_of_other_labels(dec):
    """A negative is a declared identity marker of some other label; never the label's own."""
    for L, spec in dec["labels"].items():
        own = set(spec["markers"])
        for m in spec["negatives"]:
            assert m not in own, f"{L}: {m} is both declared and negative"
            assert m in dec["identity_markers"], f"{L}: negative {m} is not a declared identity marker"


def test_identity_markers_are_disjoint_across_labels(dec):
    seen = {}
    for L, spec in dec["labels"].items():
        for m in spec["markers"]:
            assert m not in seen, f"{m} declared for both {seen[m]} and {L}"
            seen[m] = L


def test_neural_is_undeclared_with_the_recorded_reason(dec):
    assert "Neural" not in dec["labels"]
    assert "Neural" in dec["undeclared_labels"]
    assert dec["undeclared_labels"]["Neural"] == (
        "no registry type marker survives the conflict rule for this label; "
        "the label is not declared and no arm may emit it")
    # and the cause: B3TUBB, registry Neural, excluded by a definitional cross-branch claim
    assert "B3TUBB" in dec["excluded"]
    assert dec["excluded"]["B3TUBB"].startswith("registry Neural but the rule table makes a definitional claim")
    assert "B3TUBB" not in dec["identity_markers"]


def test_conflict_rule_exclusions_are_the_recorded_ones(dec):
    """The protocol's exclusions plus the new type measurements without identity rules: CD141 and
    CD21 (2026-09-16), and CD14, CD45 and Keratin_14 from the spleen PhenoCycler panel (2026-10-30)."""
    assert set(dec["excluded"]) == {"B3TUBB", "CD11b", "CD34", "CD56", "CD66", "IAPP", "b_Catenin1",
                                    "CD141", "CD21", "CD14", "CD45", "Keratin_14"}
    assert dec["excluded"]["CD11b"] == "registry kind=excluded"
    assert dec["excluded"]["IAPP"] == "registry kind=excluded"
    assert "Mes-CD34-fibroblast" in dec["excluded"]["CD34"]
    assert "Imm-neutrophil" in dec["excluded"]["CD66"]
    for m in dec["excluded"]:
        assert m not in dec["identity_markers"]


def test_registry_additions_need_rule_table_support_before_entering_identity(dec):
    """The 72-marker measurement registry includes deferred markers outside this rule table."""
    import rules
    registry = {m["name"]: m for m in pins.registry()["markers"]}
    table = rules.load_rules(pins.RULES_37)
    absent_types = {m for m, spec in registry.items()
                    if spec["kind"] == pins.KIND_TYPE and m not in table.columns}
    # CD14, CD45 and Keratin_14 came with the spleen PhenoCycler panel (2026-10-30): deferred type
    # markers the 37-reference rule table has no rule for, so they stay out of identity.
    assert absent_types == {"CD141", "CD21", "b_Catenin1", "CD14", "CD45", "Keratin_14"}
    assert absent_types <= set(dec["excluded"])
    for m in ("CD141", "CD21", "CD14", "CD45", "Keratin_14"):
        assert registry[m]["calibration_status"] == "deferred"
        assert registry[m]["uses"] == ["deferred_type"]
        assert dec["excluded"][m] == "registry type marker absent from the rule table; no identity rule declared"
    assert not absent_types & set(dec["identity_markers"])
    assert set(dec["identity_markers"]) <= set(table.columns)
    accounted = [*dec["identity_markers"], *dec["state_markers"],
                 *dec["structural_markers"], *dec["excluded"]]
    assert len(accounted) == len(set(accounted)) == len(registry)
    assert set(accounted) == set(registry)


def test_write_is_idempotent_on_the_frozen_files(tmp_path, monkeypatch):
    """Running ``write`` again must reproduce the files it wrote -- into a scratch copy here."""
    monkeypatch.setattr(declarations, "DECLARATIONS_JSON", tmp_path / "declarations.json")
    monkeypatch.setattr(declarations, "RULES_BROAD8_CSV", tmp_path / "rules_broad8.csv")
    declarations.write()
    assert (tmp_path / "declarations.json").read_bytes() == (declarations.HERE / "declarations.json").read_bytes()
    assert (tmp_path / "rules_broad8.csv").read_bytes() == (declarations.HERE / "rules_broad8.csv").read_bytes()
    # the scratch csv reads back as the v4 layout the celltype loader expects
    d = pd.read_csv(tmp_path / "rules_broad8.csv")
    assert [c for c in d.columns if str(c).startswith("Unnamed:")] == ["Unnamed: 0", "Unnamed: 1"]
