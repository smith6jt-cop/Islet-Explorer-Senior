"""Every reference to a package module or package data file must resolve.

Three separate incidents motivated this file, all the same shape: code or a
shipped script kept naming something that had been deleted, and nothing failed
until someone ran it or read it and believed it.

* ``setup.sh`` imported ``phenocycler.ordered_residual_typing`` and checked for
  ``ordered_residual_rules.json`` for a day after both were deleted, so the
  documented install verification crashed.
* ``pyproject.toml`` declared the deleted ``ordered_residual_rules.json`` as
  package data and omitted ``broad_gates.json``.
* the retired ``notebooks/03`` once still read
  ``audit/marker_calibration_models.parquet`` after its producer was deleted;
  the notebook is now removed and executable notebook cells are scanned below.

Prose about deleted modules is legitimate -- history belongs in comments and in
``docs/METHOD_HISTORY.md``. What must never dangle is an executable reference.
"""

from __future__ import annotations

import ast
import importlib.util
import re
from pathlib import Path

import pytest

# `tomllib` is stdlib only from 3.11, but `requires-python` is >=3.10 and CI runs the floor,
# so importing it unconditionally made this whole module fail collection on 3.10 — taking the
# rest of the file's checks down with it. Fall back to `tomli`, and if neither is present skip
# with a reason rather than silently: CI runs pytest with `-rs`, so a skip is visible in the
# summary, whereas a collection error is just a red job that says nothing about coverage.
try:
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - depends on the interpreter
    try:
        import tomli as tomllib
    except ModuleNotFoundError:  # pragma: no cover
        tomllib = None

pytestmark = pytest.mark.skipif(
    tomllib is None,
    reason="no TOML reader: tomllib needs Python >= 3.11 and tomli is not installed",
)

# tests/current/ is two levels below the repo root, not one: this file moved when the suite
# was split into current/research/integration lanes.
REPO = Path(__file__).resolve().parents[2]
PACKAGE = REPO / "multiplex5000"
RETIRED_EXECUTABLE_NAMES = (
    "phenocycler.marker_calibration",
    "phenocycler.marker_debug",
    "phenocycler.hierarchical_typing",
    "phenocycler.typing_stage",
    "phenocycler.probabilistic_training",
    "phenocycler.candidate_evaluation",
)


def _python_sources() -> list[Path]:
    return sorted(
        path
        for directory in (PACKAGE, REPO / "scripts")
        for path in directory.rglob("*.py")
        if "__pycache__" not in path.parts
    )


def _guarded_nodes(tree: ast.AST) -> set[int]:
    """Imports inside a `try` are allowed to be absent.

    `phenocycler._version` is generated by setuptools_scm at build time and is
    imported under `try/except ImportError`, so it legitimately does not exist in
    a source checkout. An unguarded import has no such excuse.
    """
    guarded: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Try):
            for statement in node.body:
                for inner in ast.walk(statement):
                    guarded.add(id(inner))
    return guarded


def _imported_package_modules(source: Path) -> set[str]:
    tree = ast.parse(source.read_text(), filename=str(source))
    guarded = _guarded_nodes(tree)
    modules: set[str] = set()
    for node in ast.walk(tree):
        if id(node) in guarded:
            continue
        if isinstance(node, ast.Import):
            modules.update(
                alias.name
                for alias in node.names
                if alias.name.split(".")[0] == "phenocycler"
            )
        elif isinstance(node, ast.ImportFrom):
            if node.level:  # relative import inside the package
                package = ".".join(
                    ["phenocycler", *source.relative_to(PACKAGE).parts[:-1]]
                )
                base = package if node.level == 1 else package.rsplit(".", node.level - 1)[0]
                modules.add(f"{base}.{node.module}" if node.module else base)
            elif node.module and node.module.split(".")[0] == "phenocycler":
                modules.add(node.module)
    return modules


def test_all_executable_package_imports_resolve() -> None:
    stale: list[str] = []
    for source in _python_sources():
        for module in sorted(_imported_package_modules(source)):
            if importlib.util.find_spec(module) is None:
                stale.append(f"{source.relative_to(REPO)} -> {module}")
    assert not stale, "unresolved executable package imports:\n" + "\n".join(stale)


def test_declared_entrypoints_and_setup_imports_resolve() -> None:
    """Installed and documented executable imports must name live modules."""

    config = tomllib.loads((REPO / "pyproject.toml").read_text())
    modules = {
        target.partition(":")[0]
        for target in config["project"].get("scripts", {}).values()
    }
    setup_text = (REPO / "setup.sh").read_text()
    modules.update(
        re.findall(r"^from (phenocycler[.\w]*) import", setup_text, re.MULTILINE)
    )
    stale = sorted(module for module in modules if importlib.util.find_spec(module) is None)
    assert not stale, f"entry points or setup import deleted modules: {stale}"


def test_notebook_code_does_not_name_retired_executables() -> None:
    stale = []
    for path in sorted((REPO / "notebooks").glob("*.ipynb")):
        payload = path.read_text(encoding="utf-8")
        for name in RETIRED_EXECUTABLE_NAMES:
            if name in payload:
                stale.append(f"{path.relative_to(REPO)} -> {name}")
    assert not stale, "notebook code names retired modules:\n" + "\n".join(stale)


def test_declared_package_data_exists() -> None:
    config = tomllib.loads((REPO / "pyproject.toml").read_text())
    declared = config["tool"]["setuptools"]["package-data"]["multiplex5000"]
    for name in declared:
        assert (PACKAGE / name).is_file(), (
            f"pyproject.toml declares package data {name!r}, which does not exist"
        )


def test_shipped_rules_and_stage_sources_resolve() -> None:
    """Rule files must ship, and every stage source must exist."""
    config = tomllib.loads((REPO / "pyproject.toml").read_text())
    declared = set(config["tool"]["setuptools"]["package-data"]["multiplex5000"])
    shipped = {
        path.name
        for path in PACKAGE.glob("*.json")
        if path.name != "adoption_compatibility.json"
    }
    missing = sorted(shipped - declared)
    assert not missing, f"shipped package data not declared in pyproject.toml: {missing}"

    from phenocycler.pipeline import STAGE_SOURCE_PATHS

    stale_sources = sorted(
        path
        for paths in STAGE_SOURCE_PATHS.values()
        for path in paths
        if not (REPO / path).is_file()
    )
    assert not stale_sources, f"stage source paths do not exist: {stale_sources}"
